/**
 * Render any icon (key, legacy emoji, or SVG string).
 */
export function getHabitSvg(iconOrKey, size = 18) {
  if (!iconOrKey) return ICONS_SVG['target'];

  // Already an SVG?
  if (typeof iconOrKey === 'string' && iconOrKey.trim().startsWith('<svg')) {
    return iconOrKey;
  }

  // Known key?
  if (ICONS_SVG[iconOrKey]) {
    return formatSvg(ICONS_SVG[iconOrKey], size);
  }

  // Mapped from legacy emoji?
  const mapped = EMOJI_TO_KEY[iconOrKey];
  if (mapped && ICONS_SVG[mapped]) {
    return formatSvg(ICONS_SVG[mapped], size);
  }

  // Fallback to minimal target glyph
  return formatSvg(ICONS_SVG['target'], size);
}

